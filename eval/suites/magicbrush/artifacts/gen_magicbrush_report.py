#!/usr/bin/env python
"""Persist a MagicBrush cross-checkpoint comparison table.

Reads evaluation_metrics.json out of each `results/<model>/` dir under this
suite and writes one markdown table (final_turn + all_turn) to
`magicbrush_comparison.md` in this directory. Supersedes the old
`aggregate_results.py`, which only printed to stdout and never persisted
anything -- this repo's convention (see eval/suites/vbvr/artifacts/) is a
committed, human-readable report artifact per suite.

Usage (no GPU / heavy deps needed, just reads json):
  python gen_magicbrush_report.py
"""
import json
import os

METRICS = ["l1", "l2", "clip-i", "dino", "clip-t"]

_HERE = os.path.dirname(os.path.abspath(__file__))
_SUITE_ROOT = os.path.abspath(os.path.join(_HERE, ".."))
RESULTS_ROOT = os.path.join(_SUITE_ROOT, "results")
OUT_MD = os.path.join(_HERE, "magicbrush_comparison.md")

# Ordered so `base` leads the table, then its SSL/fine-tuned variants.
MODEL_ORDER = [
    "InternVL-U",
    "InternVL-U-s0-pretrain",
    "InternVL-U-s1-pretrain",
    "InternVL-U-s2-pretrain",
    "InternVL-U-s3-pretrain",
    "InternVL-U-s4-pretrain",
    "InternVL-U-ffs-sft",
    "InternVL-U-gen-sft-vae",
    "InternVL-U-dualssl-leak",
    "InternVL-U-nwm-gen-action",
    "InternVL-U-nwm-gen-noaction",
    "InternVL-U-nwm-dual-action",
    "InternVL-U-nwm-dual-noaction",
    "InternVL-U-nwm-edit-action",
]


def main():
    rows = {}
    for name in MODEL_ORDER:
        path = os.path.join(RESULTS_ROOT, name, "evaluation_metrics.json")
        if not os.path.exists(path):
            print(f"[report] SKIP {name}: no evaluation_metrics.json at {path}")
            continue
        rows[name] = json.load(open(path))
    # Pick up anything present under results/ but not in MODEL_ORDER too.
    for name in sorted(os.listdir(RESULTS_ROOT)) if os.path.isdir(RESULTS_ROOT) else []:
        if name in rows:
            continue
        path = os.path.join(RESULTS_ROOT, name, "evaluation_metrics.json")
        if os.path.exists(path):
            rows[name] = json.load(open(path))

    lines = [
        "# MagicBrush — InternVL-U checkpoint comparison",
        "",
        "Single-turn (\"independent editing\") instruction-based image editing.",
        "Metrics: L1/L2 (lower better), CLIP-I / DINO / CLIP-T (higher better).",
        "Generated by `gen_magicbrush_report.py` from `../results/<model>/evaluation_metrics.json`.",
        "",
    ]
    for split in ["final_turn", "all_turn"]:
        lines.append(f"## {split}")
        lines.append("")
        header = ["model"] + METRICS
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|" + "---|" * len(header))
        for name, data in rows.items():
            vals = data.get(split, {})
            cells = [name] + [f"{vals.get(m, float('nan')):.4f}" for m in METRICS]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")

    with open(OUT_MD, "w") as f:
        f.write("\n".join(lines))
    print(f"[report] wrote {OUT_MD} ({len(rows)} models)")


if __name__ == "__main__":
    main()
